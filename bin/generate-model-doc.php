<?php

declare(strict_types=1);

/*
 * Generates docs/MODEL.md, the table mapping EN 16931 business terms (BT-*) and groups (BG-*)
 * to the classes and properties of IntrAgile\EInvoicing\Model. The term ids are read from the
 * PHPDoc of the model classes and their properties, so the table cannot drift from the code.
 *
 *   php bin/generate-model-doc.php            writes docs/MODEL.md
 *   php bin/generate-model-doc.php --check    exits 1 when docs/MODEL.md is missing or stale
 *   php bin/generate-model-doc.php --stdout   prints the page instead of writing it
 *
 * The output depends only on the source tree: rows are sorted by term id, then class, then
 * property.
 */

require __DIR__.'/../vendor/autoload.php';

const TARGET = __DIR__.'/../docs/MODEL.md';
const MODEL_DIR = __DIR__.'/../src/Model';
const MODEL_NAMESPACE = 'IntrAgile\\EInvoicing\\Model\\';
const TERM_PATTERN = '/\b(?:BT|BG)-\d+(?:-\d+)?\b/';

/**
 * Strips PHPDoc decoration, joins the lines and drops tag lines.
 */
function summary(string|false $doc): string
{
    if ($doc === false) {
        return '';
    }
    $lines = [];
    foreach (preg_split('/\R/', $doc) ?: [] as $line) {
        $line = trim($line, " \t/*");
        if ($line === '' || str_starts_with($line, '@')) {
            continue;
        }
        $lines[] = $line;
    }

    return implode(' ', $lines);
}

/**
 * @param  ReflectionClass<object>  $class
 * @return array{array<string, string>, array<string, string>} the text and the type of each @param
 *                                                             tag in the constructor docblock,
 *                                                             keyed by property name
 */
function paramDocs(ReflectionClass $class): array
{
    $docs = [];
    $types = [];
    $doc = $class->getConstructor()?->getDocComment();
    if ($doc === false || $doc === null) {
        return [$docs, $types];
    }
    $text = preg_replace('/\R\s*\*\s?/', "\n", $doc) ?? '';
    if (preg_match_all('/@param\s+(.+?)\s+\$(\w+)\s+(.*?)(?=\n@|\*\/|$)/s', $text, $matches, PREG_SET_ORDER) > 0) {
        foreach ($matches as $m) {
            $types[$m[2]] = $m[1];
            $docs[$m[2]] = trim((string) preg_replace('/\s+/', ' ', $m[3]));
        }
    }

    return [$docs, $types];
}

function typeName(ReflectionProperty $property, ?string $documented): string
{
    $type = str_replace(MODEL_NAMESPACE, '', (string) $property->getType());

    return $type === 'array' && $documented !== null ? $documented : $type;
}

function cell(string $text): string
{
    return str_replace('|', '\\|', $text);
}

function build(): string
{
    $files = glob(MODEL_DIR.'/*.php') ?: [];
    sort($files);
    $rows = [];
    foreach ($files as $file) {
        $short = basename($file, '.php');
        /** @var class-string $className */
        $className = MODEL_NAMESPACE.$short;
        $class = new ReflectionClass($className);
        $classDoc = summary($class->getDocComment());
        [$paramDocs, $paramTypes] = paramDocs($class);

        if (preg_match_all(TERM_PATTERN, $classDoc, $found) > 0) {
            foreach (array_unique($found[0]) as $term) {
                $rows[] = [$term, $short, '', '', $classDoc];
            }
        }
        foreach ($class->getProperties() as $property) {
            $doc = summary($property->getDocComment());
            if ($doc === '' || preg_match(TERM_PATTERN, $doc) !== 1) {
                $doc = $paramDocs[$property->getName()] ?? $doc;
            }
            if (preg_match_all(TERM_PATTERN, $doc, $found) === 0) {
                continue;
            }
            foreach (array_unique($found[0]) as $term) {
                $rows[] = [$term, $short, '$'.$property->getName(), typeName($property, $paramTypes[$property->getName()] ?? null), $doc];
            }
        }
    }

    usort($rows, static function (array $a, array $b): int {
        return [termKey($a[0]), $a[1], $a[2]] <=> [termKey($b[0]), $b[1], $b[2]];
    });

    $out = "# Model reference\n\n";
    $out .= "Developed and maintained by [IntrAgile Kft.](https://intragile.eu)\n\n";
    $out .= "Where each EN 16931-1 business term (BT) and business group (BG) lives in the\n";
    $out .= "`IntrAgile\\EInvoicing\\Model` namespace. Generated by `bin/generate-model-doc.php` from the\n";
    $out .= "PHPDoc of the model classes; do not edit by hand. A row without a property is the class\n";
    $out .= "that represents the whole group. Where a property documents several ids (for example\n";
    $out .= "seller, buyer and payee names), it appears once per id.\n\n";
    $out .= "| Term | Class | Property | Type | Description |\n";
    $out .= "| --- | --- | --- | --- | --- |\n";
    foreach ($rows as [$term, $class, $property, $type, $doc]) {
        $out .= sprintf(
            "| %s | `%s` | %s | %s | %s |\n",
            $term,
            $class,
            $property === '' ? '' : '`'.$property.'`',
            $type === '' ? '' : '`'.cell($type).'`',
            cell($doc),
        );
    }
    $out .= "\n## Country extensions\n\n";
    $out .= "Country data EN 16931 does not carry is attached through the extension bags of `Invoice`\n";
    $out .= "and `InvoiceLine` (`withExtension()`, `extensions()->get()`), outside this table:\n\n";
    $out .= "- France: `IntrAgile\\EInvoicing\\France\\FrenchInvoice` and `FrenchLine`, see\n";
    $out .= "  [countries/FRANCE.md](countries/FRANCE.md).\n";
    $out .= "- Poland: `IntrAgile\\EInvoicing\\Poland\\PolishInvoice` (invoice kind, annotations, Polish party\n";
    $out .= "  data, correction data, advances, VAT in PLN, charges and deductions, payment form, bank\n";
    $out .= "  accounts, transaction terms, verbatim blocks) and `PolishLine` (P_12 rate code, unit label,\n";
    $out .= "  GTU, procedure, state-before, margin and bucket-line flags), see\n";
    $out .= "  [countries/POLAND.md](countries/POLAND.md).\n";
    $out .= "\n---\n\nDeveloped and maintained by [IntrAgile Kft.](https://intragile.eu)\n";

    return $out;
}

/**
 * @return array{int, int, int}
 */
function termKey(string $term): array
{
    if (preg_match('/^(BT|BG)-(\d+)(?:-(\d+))?$/', $term, $m) !== 1) {
        throw new InvalidArgumentException('Not a term id: '.$term);
    }

    return [$m[1] === 'BG' ? 0 : 1, (int) $m[2], (int) ($m[3] ?? 0)];
}

$mode = $argv[1] ?? '';
$page = build();

if ($mode === '--stdout') {
    echo $page;
    exit(0);
}
if ($mode === '--check') {
    if (! is_file(TARGET) || file_get_contents(TARGET) !== $page) {
        fwrite(STDERR, "docs/MODEL.md is missing or stale; run php bin/generate-model-doc.php\n");
        exit(1);
    }
    exit(0);
}
if (! is_dir(dirname(TARGET))) {
    mkdir(dirname(TARGET), 0777, true);
}
file_put_contents(TARGET, $page);
echo "Wrote docs/MODEL.md\n";
