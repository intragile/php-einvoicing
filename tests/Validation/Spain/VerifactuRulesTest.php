/**
 * The published VERI*FACTU business rules: each rule reported on a schema-valid record edited to
 * break it (verifactu-rule-cases.php).
 *
 * A case is ['rule' => id, 'base' => name, 'edits' => Mutator edits with the prefix "sf"]. The base
 * is a B2Brouter record file name (ending in ".xml") or the name of a sample of samples(). Every
 * edit that touches a hashed field would also break the Huella, so after the edits each record's
 * Huella is recomputed, except in the cases of ES-VF-23, which break the Huella on purpose.
 */
#[Group('verifactu-official')]
final class VerifactuRulesTest extends TestCase
{
    public const NAMESPACES = ['sf' => VerifactuFormat::SF_NS, 'lr' => VerifactuFormat::LR_NS];

    /**
     * Records generated by this library and dated after 28 October 2024: two chained altas and the
     * cancellation of the second, by name.
     *
     * @return array<string, string>
     */
    public static function samples(): array
    {
        $system = VerifactuSamples::system();
        $first = RegistrationRecord::create(
            VerifactuSamples::vectorDraft('12345678/G33', '01-11-2024'),
            ChainLink::first(),
            $system,
            RecordTimestamp::fromLiteral('2024-11-01T19:20:30+01:00'),
        );
        $second = RegistrationRecord::create(
            VerifactuSamples::vectorDraft('12345679/G34', '01-11-2024'),
            ChainLink::after($first->invoiceId(), $first->fingerprint()),
            $system,
            RecordTimestamp::fromLiteral('2024-11-01T19:20:35+01:00'),
        );
        $cancellation = CancellationRecord::create(
            CancellationDraft::of(VerifactuSamples::invoiceId('12345679/G34', '01-11-2024')),
            ChainLink::after($second->invoiceId(), $second->fingerprint()),
            $system,
            RecordTimestamp::fromLiteral('2024-11-01T19:20:40+01:00'),
        );
        $writer = new RecordWriter;

        return [
            'alta' => $writer->write($first),
            'second' => $writer->write($second),
            'anulacion' => $writer->write($cancellation),
        ];
    }

    /**
     * @return array<string, array{string, string, list<array<int, string>>}>
     */
    public static function cases(): array
    {
        $cases = [];
        foreach (self::caseList() as $case) {
            $name = $case['rule'];
            for ($n = 2; isset($cases[$name]); $n++) {
                $name = $case['rule'].':'.$n;
            }
            $cases[$name] = [$case['rule'], $case['base'], $case['edits']];
        }

        return $cases;
    }

    /**
     * @param  list<array<int, string>>  $edits
     */
    #[DataProvider('cases')]
    public function test_case_fires_its_rule(string $rule, string $base, array $edits): void
    {
        $xml = Mutator::apply(self::base($base), $edits, self::NAMESPACES);
        if ($rule !== 'ES-VF-23') {
            $xml = self::rehash($xml);
        }

        $report = self::validator()->validate($xml);

        self::assertSame([], self::schemaMessages($report), 'A case must stay schema-valid.');
        $definition = VerifactuRules::rules()[$rule];
        self::assertSame(["{$rule} {$definition['severity']->value}"], $report->verdict(), implode("\n", self::describe($report->findings)));
        foreach ($report->findings as $finding) {
            self::assertMatchesRegularExpression('/\AValidaciones v1\.2\.2 §[^;]+; AEAT error (\d{4})\z/', $finding->test);
            self::assertContains(substr($finding->test, -4), explode(', ', $definition['code']), $finding->test);
        }
    }

    public function test_every_case_base_is_clean(): void
    {
        foreach (array_unique(array_column(self::caseList(), 'base')) as $base) {
            $report = self::validator()->validate(self::base($base));
            self::assertSame([], self::schemaMessages($report), $base);
            self::assertSame([], self::describe($report->findings), $base);
        }
    }

    public function test_every_rule_has_a_case(): void
    {
        $covered = array_unique(array_column(self::caseList(), 'rule'));

        self::assertSame([], array_values(array_diff(array_keys(VerifactuRules::rules()), $covered)));
        self::assertSame([], array_values(array_diff($covered, array_keys(VerifactuRules::rules()))));
    }

    public function test_every_rule_cites_a_section_and_code(): void
    {
        $ids = array_map(static fn (int $n): string => sprintf('ES-VF-%02d', $n), range(1, 24));
        self::assertSame($ids, array_keys(VerifactuRules::rules()));
        self::assertSame('es-verifactu', VerifactuRules::ID);
        self::assertSame('1.2.2', VerifactuRules::VERSION);

        foreach (VerifactuRules::rules() as $id => $rule) {
            self::assertMatchesRegularExpression('/\A§3\.1\.[34]\.\d+/', $rule['source'], $id);
            self::assertMatchesRegularExpression('/\A[12]\d{3}(, [12]\d{3})*\z/', $rule['code'], $id);
            $expected = in_array($id, ['ES-VF-21', 'ES-VF-22', 'ES-VF-23', 'ES-VF-24'], true) ? Severity::Warning : Severity::Fatal;
            self::assertSame($expected, $rule['severity'], $id);
        }
    }

    public function test_tampered_huella_fires_es_vf_23(): void
    {
        $xml = Fixtures::verifactuB2Brouter()['record-1064493.xml'];
        $tampered = str_replace('D60F9FD2DDDD', 'D60F9FD2DDDE', $xml);
        self::assertNotSame($xml, $tampered);

        $report = self::validator()->validate($tampered);

        self::assertSame([], self::schemaMessages($report));
        self::assertSame(['ES-VF-23 warning'], $report->verdict());
        self::assertSame('/sum1:RegistroAlta[1]/sum1:Huella[1]', $report->findings[0]->location);
        self::assertSame('Validaciones v1.2.2 §3.1.3.23, §3.1.4.7; AEAT error 2000', $report->findings[0]->test);
        self::assertStringContainsString('D60F9FD2DDDD19313359612C52222CC74E0B7C6E3C0D64AFBC797F2CE54EF812', $report->findings[0]->message);
        self::assertTrue($report->isValid());
    }

    public function test_lower_case_own_huella_fires_es_vf_23(): void
    {
        $xml = Mutator::apply(Fixtures::verifactuB2Brouter()['record-1064493.xml'], [
            ['/sf:RegistroAlta/sf:Huella', 'set', 'd60f9fd2dddd19313359612c52222cc74e0b7c6e3c0d64afbc797f2ce54ef812'],
        ], self::NAMESPACES);

        self::assertSame(['ES-VF-23 warning'], self::validator()->validate($xml)->verdict());
    }

    public function test_previous_huella_equal_to_own_fires_es_vf_24(): void
    {
        $xml = Mutator::apply(Fixtures::verifactuB2Brouter()['record-1064493.xml'], [
            ['/sf:RegistroAlta/sf:Encadenamiento/sf:RegistroAnterior/sf:Huella', 'set', 'D60F9FD2DDDD19313359612C52222CC74E0B7C6E3C0D64AFBC797F2CE54EF812'],
        ], self::NAMESPACES);

        $report = self::validator()->validate($xml);

        // The previous Huella is hashed too, so the own Huella no longer matches either.
        self::assertSame(['ES-VF-23 warning', 'ES-VF-24 warning'], $report->verdict());
        $tests = array_map(static fn (Finding $finding): string => $finding->test, $report->findings);
        self::assertContains('Validaciones v1.2.2 §3.1.3.18, §3.1.4.4; AEAT error 2008', $tests);
    }

    public function test_cuota_within_ten_euros_passes(): void
    {
        $quota = static fn (string $value): MessageValidationReport => self::validator()->validate(self::rehash(Mutator::apply(
            self::base('record-1064493.xml'),
            [
                ['/sf:RegistroAlta/sf:Desglose/sf:DetalleDesglose/sf:BaseImponibleOimporteNoSujeto', 'set', '100.00'],
                ['/sf:RegistroAlta/sf:Desglose/sf:DetalleDesglose/sf:TipoImpositivo', 'set', '21'],
                ['/sf:RegistroAlta/sf:Desglose/sf:DetalleDesglose/sf:CuotaRepercutida', 'set', $value],
                ['/sf:RegistroAlta/sf:CuotaTotal', 'set', $value],
                ['/sf:RegistroAlta/sf:ImporteTotal', 'set', (string) (100 + (float) $value)],
            ],
            self::NAMESPACES,
        )));

        self::assertSame([], $quota('31.00')->verdict());
        self::assertSame([], $quota('11.00')->verdict());
        self::assertSame(['ES-VF-19 fatal'], $quota('31.01')->verdict());
        self::assertSame(['ES-VF-19 fatal'], $quota('10.99')->verdict());
    }

    public function test_correction_by_difference_skips_the_quota_check(): void
    {
        $xml = self::rehash(Mutator::apply(self::base('record-1064501.xml'), [
            ['/sf:RegistroAlta/sf:Desglose/sf:DetalleDesglose/sf:CuotaRepercutida', 'set', '50.00'],
            ['/sf:RegistroAlta/sf:CuotaTotal', 'set', '50.00'],
            ['/sf:RegistroAlta/sf:ImporteTotal', 'set', '150.00'],
        ], self::NAMESPACES));

        self::assertSame([], self::validator()->validate($xml)->verdict());
    }

    public function test_sum_checks_skip_special_regimes(): void
    {
        $xml = self::rehash(Mutator::apply(self::base('record-1064493.xml'), [
            ['/sf:RegistroAlta/sf:Desglose/sf:DetalleDesglose/sf:ClaveRegimen', 'set', '05'],
            ['/sf:RegistroAlta/sf:CuotaTotal', 'set', '99.00'],
            ['/sf:RegistroAlta/sf:ImporteTotal', 'set', '999.00'],
        ], self::NAMESPACES));

        self::assertSame([], self::validator()->validate($xml)->verdict());
    }

    public function test_amounts_compare_as_decimals(): void
    {
        $totals = static fn (string $quota, string $total): MessageValidationReport => self::validator()->validate(self::rehash(Mutator::apply(
            self::base('record-1064493.xml'),
            [['/sf:RegistroAlta/sf:CuotaTotal', 'set', $quota], ['/sf:RegistroAlta/sf:ImporteTotal', 'set', $total]],
            self::NAMESPACES,
        )));

        self::assertSame([], $totals('+31.00', '111.')->verdict());
        self::assertSame(['ES-VF-21 warning', 'ES-VF-22 warning'], $totals('+31.01', '110.9')->verdict());
    }

    /**
     * AEAT's example writes "41.4" and "241.4"; its published Huella is the hash of that literal
     * text, and its regime 05 line exempts it from the sum checks.
     */
    public function test_aeat_example_record_is_clean(): void
    {
        $report = self::validator()->validate((string) file_get_contents(Fixtures::verifactuExample()));

        self::assertSame([], self::schemaMessages($report));
        self::assertSame([], self::describe($report->findings));
    }

    /**
     * Replaces the Huella of every record by the fingerprint of its literal text.
     */
    public static function rehash(string $xml): string
    {
        $document = SafeXml::load($xml);
        $xpath = new DOMXPath($document);
        $xpath->registerNamespace('sf', VerifactuFormat::SF_NS);
        foreach ($xpath->query('//sf:RegistroAlta | //sf:RegistroAnulacion') ?: [] as $record) {
            self::assertInstanceOf(DOMElement::class, $record);
            $huella = null;
            foreach ($record->childNodes as $child) {
                if ($child instanceof DOMElement && $child->localName === 'Huella') {
                    $huella = $child;
                }
            }
            self::assertInstanceOf(DOMElement::class, $huella);
            $huella->textContent = Fingerprint::recompute($record);
        }

        return (string) $document->saveXML();
    }

    public static function base(string $name): string
    {
        $records = str_ends_with($name, '.xml') ? Fixtures::verifactuB2Brouter() : self::samples();
        self::assertArrayHasKey($name, $records);

        return $records[$name];
    }

    public static function validator(): VerifactuValidator
    {
        return VerifactuValidator::create(Fixtures::verifactuSchemas());
    }

    /**
     * @return list<string>
     */
    public static function schemaMessages(MessageValidationReport $report): array
    {
        return array_map(static fn (SchemaError $error): string => $error->message, $report->schemaErrors);
    }

    /**
     * @param  list<Finding>  $findings
     * @return list<string>
     */
    public static function describe(array $findings): array
    {
        return array_map(
            static fn (Finding $finding): string => "{$finding->ruleId} {$finding->severity->value} {$finding->location}: {$finding->message} ({$finding->test})",
            $findings,
        );
    }

    /**
     * @return list<array{rule: string, base: string, edits: list<array<int, string>>}>
     */
    private static function caseList(): array
    {
        /** @var list<array{rule: string, base: string, edits: list<array<int, string>>}> */
        return require __DIR__.'/verifactu-rule-cases.php';
    }
}
